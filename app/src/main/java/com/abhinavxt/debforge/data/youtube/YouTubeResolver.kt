/** Why a link could not be resolved; the UI picks its message from the subtype. */
sealed class YouTubeException(message: String, cause: Throwable? = null) : Exception(message, cause) {
    class PlaylistOnly : YouTubeException("Playlists aren't supported; open a single video")
    class SignInRequired(cause: Throwable? = null) : YouTubeException("Age restricted or sign-in required", cause)
    class Unavailable(message: String = "Video unavailable or private", cause: Throwable? = null) : YouTubeException(message, cause)
    class Network(cause: Throwable?) : YouTubeException("Network error", cause)
    class Failed(cause: Throwable?) : YouTubeException(cause?.message ?: "Could not read the video", cause)
}

@Singleton
class YouTubeResolver @Inject constructor(@ApiHttpClient private val client: OkHttpClient) {
    private val init by lazy { NewPipe.init(NewPipeDownloader(client), Localization("en", "US")) }

    suspend fun resolve(url: String): YouTubeVideo = BlockingCalls.run {
        val id = YouTubeLinks.videoId(url)
            ?: throw if (YouTubeLinks.isPlaylistOnly(url)) YouTubeException.PlaylistOnly()
            else YouTubeException.Unavailable("Not a YouTube video link")
        val info = try {
            init
            StreamInfo.getInfo("https://www.youtube.com/watch?v=$id")
        } catch (e: Exception) {
            throw map(e)
        }
        YouTubeVideo(
            id = id,
            title = info.name.orEmpty(),
            uploader = info.uploaderName.orEmpty(),
            uploaderUrl = info.uploaderUrl?.takeIf { it.isNotBlank() },
            durationSec = info.duration,
            thumbnailUrl = info.thumbnails.maxByOrNull { it.height }?.url,
            streams = info.videoOnlyStreams.mapNotNull { video(it) } + info.audioStreams.mapNotNull { audio(it) },
            // StreamInfo only lists TTML tracks; YouTube serves the same track as WebVTT with fmt=vtt.
            subtitles = info.subtitles.filter { it.isUrl && it.format == MediaFormat.TTML && !it.languageTag.isNullOrBlank() }
                .map { YouTubeSubtitle(it.languageTag, it.displayLanguageName.orEmpty().ifBlank { it.languageTag }, withVttFormat(it.content), it.isAutoGenerated) }
                .onePerLanguage(),
        )
    }

    /** One page of search results and the extractor's cursor for the next, null at the end. */
    class SearchPage(val items: List<YouTubeSearchResult>, val next: Page?)

    suspend fun search(query: String): SearchPage = withContext(Dispatchers.IO) {
        try {
            init
            val info = SearchInfo.getInfo(ServiceList.YouTube, searchHandler(query))
            SearchPage(searchResults(info.relatedItems), info.nextPage)
        } catch (e: Exception) {
            throw map(e)
        }
    }

    suspend fun searchMore(query: String, page: Page): SearchPage = withContext(Dispatchers.IO) {
        try {
            init
            val more = SearchInfo.getMoreItems(ServiceList.YouTube, searchHandler(query), page)
            SearchPage(searchResults(more.items), more.nextPage)
        } catch (e: Exception) {
            throw map(e)
        }
    }

    private fun searchHandler(query: String) =
        ServiceList.YouTube.searchQHFactory.fromQuery(query, listOf(YoutubeSearchQueryHandlerFactory.VIDEOS), "")

    private fun searchResults(items: List<InfoItem>) = items.filterIsInstance<StreamInfoItem>().map {
        YouTubeSearchResult(it.url, it.name.orEmpty(), it.uploaderName, it.duration, it.thumbnails.maxByOrNull { t -> t.height }?.url, it.uploaderUrl)
    }.distinctBy { it.url } // rows are keyed by url; a repeat would crash the list

    /** The trending-music kiosk's first page (at most 30); callers treat any failure as "no trending". */
    suspend fun trending(): List<YouTubeSearchResult> = withContext(Dispatchers.IO) {
        init
        // The default kiosk is live streams, which cannot be saved; YouTube dropped its general Trending page.
        val kiosk = ServiceList.YouTube.kioskList.getExtractorById("trending_music", null)
        kiosk.fetchPage()
        searchResults(KioskInfo.getInfo(kiosk).relatedItems).take(30)
    }

    // shortcut: handlers are kept for the process lifetime, one per visited channel; evict if that ever matters
    private val channelTabs = ConcurrentHashMap<String, ListLinkHandler>()

    private fun videosTab(channelUrl: String) = channelTabs.getOrPut(channelUrl) {
        ChannelInfo.getInfo(ServiceList.YouTube, channelUrl).tabs.firstOrNull { ChannelTabs.VIDEOS in it.contentFilters }
            ?: throw YouTubeException.Unavailable("Channel has no videos")
    }

    suspend fun channelVideos(channelUrl: String): SearchPage = withContext(Dispatchers.IO) {
        try {
            init
            val info = ChannelTabInfo.getInfo(ServiceList.YouTube, videosTab(channelUrl))
            SearchPage(searchResults(info.relatedItems), info.nextPage)
        } catch (e: Exception) {
            throw map(e)
        }
    }

    suspend fun channelMore(channelUrl: String, page: Page): SearchPage = withContext(Dispatchers.IO) {
        try {
            init
            val more = ChannelTabInfo.getMoreItems(ServiceList.YouTube, videosTab(channelUrl), page)
            SearchPage(searchResults(more.items), more.nextPage)
        } catch (e: Exception) {
            throw map(e)
        }
    }

    suspend fun playlist(url: String): YouTubePlaylist = withContext(Dispatchers.IO) {
        try {
            init
            val listUrl = YouTubeLinks.playlistUrl(url) ?: throw YouTubeException.Unavailable("Not a YouTube playlist link")
            val info = PlaylistInfo.getInfo(listUrl)
            val items = info.relatedItems.filterIsInstance<StreamInfoItem>().toMutableList()
            var page = info.nextPage
            // shortcut: first 200 videos of a playlist, raise or page lazily when users ask
            while (page != null && items.size < 200) {
                // A later page failing, or coming back empty, keeps what already loaded.
                val more = try { PlaylistInfo.getMoreItems(ServiceList.YouTube, listUrl, page) } catch (e: Exception) { break }
                if (more.items.isEmpty()) break
                items += more.items.filterIsInstance<StreamInfoItem>()
                page = more.nextPage
            }
            YouTubePlaylist(
                info.name.orEmpty(),
                items.take(200).map {
                    YouTubeSearchResult(it.url, it.name.orEmpty(), it.uploaderName, it.duration, it.thumbnails.maxByOrNull { t -> t.height }?.url, it.uploaderUrl)
                }.distinctBy { it.url }, // rows are keyed by url; a repeat would crash the list
            )
        } catch (e: Exception) {
            throw map(e)
        }
    }

    private fun map(e: Exception): YouTubeException = when {
        e is YouTubeException -> e
        e is AgeRestrictedContentException || e is SignInConfirmNotBotException || e is ReCaptchaException ->
            YouTubeException.SignInRequired(e)
        e is ContentNotAvailableException -> YouTubeException.Unavailable(cause = e)
        generateSequence<Throwable>(e) { it.cause }.any { it is IOException } -> YouTubeException.Network(e)
        else -> YouTubeException.Failed(e)
    }

    private fun container(suffix: String?) = when (suffix) {
        "mp4" -> Container.MP4
        "m4a" -> Container.M4A
        "webm" -> Container.WEBM
        else -> null
    }

    private fun video(s: VideoStream): YouTubeStream? {
        if (!s.isUrl) return null
        return YouTubeStream(
            s.itag, s.content, StreamKind.VIDEO, container(s.format?.suffix) ?: return null, s.codec.orEmpty(),
            s.height, s.fps, s.bitrate.toLong(), s.itagItem?.contentLength ?: -1,
        )
    }

    private fun audio(s: AudioStream): YouTubeStream? {
        if (!s.isUrl || (s.audioTrackType != null && s.audioTrackType != AudioTrackType.ORIGINAL)) return null
        return YouTubeStream(
            s.itag, s.content, StreamKind.AUDIO, container(s.format?.suffix) ?: return null, s.codec.orEmpty(),
            bitrateBps = s.bitrate.toLong(), contentLength = s.itagItem?.contentLength ?: -1,
        )
    }
}
